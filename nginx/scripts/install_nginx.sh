#!/bin/bash

# Завершать скрипт немедленно, если любая команда завершилась ошибкой
set -e

# Проверка прав root
if [ "$EUID" -ne 0 ]; then
    echo "Ошибка: Нужны повышенные привилегии, используйте: sudo $0"
    exit 1
fi

# Вычисляем правильный домашний каталог пользователя, запустившего sudo
REAL_HOME=$(eval echo "~${SUDO_USER:-$USER}")

# Теперь безопасно объявляем пути к файлам через $REAL_HOME
DEB_PACKAGE="${REAL_HOME}/packages/nginx_1.24.0-2ubuntu7.15_amd64.deb"
NEW_CONFIG="${REAL_HOME}/linux_basic_project/configs/nginx.conf"
TARGET_CONFIG="/etc/nginx/sites-available/default"

# Проверка наличия deb-пакета
if [ ! -f "$DEB_PACKAGE" ]; then
    echo "Ошибка: Пакет не найден по пути: $DEB_PACKAGE"
    exit 1
fi

echo "============================================================"
echo "Установка Nginx из локального пакета"
echo "============================================================"
# apt install умеет ставить локальные .deb и автоматически докачивать зависимости
apt install "$DEB_PACKAGE" -y

echo "============================================================"
echo "Копирование файла конфигурации"
echo "============================================================"
if [ -f "$NEW_CONFIG" ]; then
    cp "$NEW_CONFIG" "$TARGET_CONFIG"
else
    echo "Ошибка: Файл конфигурации $NEW_CONFIG не найден!"
    exit 1
fi

echo "Проверка синтаксиса конфигурации Nginx..."
nginx -t

echo "============================================================"
echo "Включение и перезапуск службы Nginx"
echo "============================================================"
systemctl enable --now nginx
systemctl reload nginx

echo "============================================================"
echo "Установка Nginx завершена. Запустите файл 02_install-apache.sh"
echo "============================================================"
