#!/bin/bash

# Завершать скрипт немедленно, если любая команда завершилась ошибкой
set -e

# Проверка прав root
if [ "$EUID" -ne 0 ]; then
    echo "Ошибка: Нужны повышенные привилегии, используйте: sudo $0"
    exit 1
fi

# Вычисляем правильный домашний каталог пользователя, запустившего sudo
REAL_HOME=$(eval echo "~${SUDO_USER:-$USER}")

# Теперь безопасно объявляем путь к deb-пакету
DEB_PACKAGE="${REAL_HOME}/packages/prometheus-node-exporter_1.7.0-1ubuntu0.3_amd64.deb"

# Проверка наличия deb-пакета
if [ ! -f "$DEB_PACKAGE" ]; then
    echo "Ошибка: Пакет не найден по пути: $DEB_PACKAGE"
    exit 1
fi

echo "============================================================"
echo "Установка Prometheus Node Exporter из локального пакета"
echo "============================================================"
apt install "$DEB_PACKAGE" -y

echo "============================================================"
echo "Включение и запуск службы Prometheus Node Exporter"
echo "============================================================"
# Включаем автозапуск и запускаем службу
systemctl enable --now prometheus-node-exporter

# Проверяем, что служба успешно запустилась и работает
if systemctl is-active --quiet prometheus-node-exporter; then
    echo "Служба prometheus-node-exporter успешно запущена!"
else
    echo "Ошибка: Служба не смогла запуститься."
    exit 1
fi

echo "============================================================"
echo "Установка завершена. Метрики доступны по порту :9100"
echo "============================================================"
